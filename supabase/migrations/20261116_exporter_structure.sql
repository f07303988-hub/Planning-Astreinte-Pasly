-- Structure complète de la base (schéma public) sous forme de script SQL,
-- pour la joindre à la sauvegarde : tables, contraintes, index, fonctions,
-- vues, sécurité par ligne, déclencheurs, droits et tâches programmées.
-- Le fichier JSON de la sauvegarde contient les données ; ce script permet
-- de recréer la base vide sur un nouveau projet avant de les recharger.
-- Réservée au serveur (clé service_role) : appelée par la fonction « sauvegarde ».
CREATE OR REPLACE FUNCTION public.exporter_structure()
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v text;
  r record;
  nl constant text := E'\n';
begin
  v := '-- Structure de la base « Astreinte - Pasly » (schéma public), générée le '
    || to_char(now() at time zone 'Europe/Paris', 'DD/MM/YYYY à HH24:MI') || '.' || nl
    || '-- À exécuter sur un projet Supabase vide, AVANT de recharger les données du fichier JSON.' || nl
    || '-- Prérequis : extensions pg_cron, pg_net, pgcrypto et supabase_vault activées ; secret' || nl
    || '-- « cle_service_fonctions » (clé service_role) créé dans le coffre-fort (Vault) ; fonctions' || nl
    || '-- serveur du dépôt GitHub déployées, avec leurs secrets BREVO_API_KEY et BREVO_SENDER_EMAIL.' || nl
    || '-- Les tables techniques (liens d''agenda, accès externes, clés des alertes, abonnements des' || nl
    || '-- téléphones) sont recréées vides : elles ne font pas partie de la sauvegarde des données.' || nl
    || '-- Les comptes de connexion sont à recréer depuis l''onglet Agents.' || nl || nl
    || 'set check_function_bodies = off;' || nl;

  v := v || nl || '-- [tables]' || nl;
  for r in
    select c.oid, c.relname from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' order by c.oid
  loop
    v := v || 'create table public.' || quote_ident(r.relname) || ' (' || nl
      || (select string_agg(
            '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
            || case a.attidentity when 'a' then ' generated always as identity'
                                  when 'd' then ' generated by default as identity' else '' end
            || case when d.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
            || case when a.attnotnull then ' not null' else '' end,
            ',' || nl order by a.attnum)
          from pg_attribute a
          left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
          where a.attrelid = r.oid and a.attnum > 0 and not a.attisdropped)
      || nl || ');' || nl;
  end loop;

  v := v || nl || '-- [cles primaires, unicite, controles]' || nl;
  for r in
    select c.relname, k.conname, pg_get_constraintdef(k.oid) as def
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace = 'public'::regnamespace and k.contype in ('p', 'u', 'c')
    order by c.oid, case k.contype when 'p' then 1 when 'u' then 2 else 3 end, k.conname
  loop
    v := v || 'alter table public.' || quote_ident(r.relname) || ' add constraint ' || quote_ident(r.conname) || ' ' || r.def || ';' || nl;
  end loop;

  v := v || nl || '-- [cles etrangeres]' || nl;
  for r in
    select c.relname, k.conname, pg_get_constraintdef(k.oid) as def
    from pg_constraint k join pg_class c on c.oid = k.conrelid
    where k.connamespace = 'public'::regnamespace and k.contype = 'f'
    order by c.oid, k.conname
  loop
    v := v || 'alter table public.' || quote_ident(r.relname) || ' add constraint ' || quote_ident(r.conname) || ' ' || r.def || ';' || nl;
  end loop;

  v := v || nl || '-- [index]' || nl;
  for r in
    select pg_get_indexdef(i.indexrelid) as def
    from pg_index i join pg_class c on c.oid = i.indrelid
    where c.relnamespace = 'public'::regnamespace
      and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
    order by c.oid, i.indexrelid
  loop
    v := v || r.def || ';' || nl;
  end loop;

  v := v || nl || '-- [fonctions]' || nl;
  for r in
    select pg_get_functiondef(p.oid) as def from pg_proc p
    where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' order by p.proname, p.oid
  loop
    v := v || rtrim(replace(r.def, E'\r', ''), E'\n ') || ';' || nl || nl;
  end loop;

  v := v || '-- [vues]' || nl;
  for r in
    select c.relname, c.reloptions, pg_get_viewdef(c.oid, true) as def from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'v' order by c.oid
  loop
    v := v || 'create view public.' || quote_ident(r.relname)
      || coalesce(' with (' || array_to_string(r.reloptions, ', ') || ')', '')
      || ' as' || nl || r.def || nl;
  end loop;

  v := v || nl || '-- [securite par ligne]' || nl;
  for r in
    select c.relname from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind = 'r' and c.relrowsecurity order by c.oid
  loop
    v := v || 'alter table public.' || quote_ident(r.relname) || ' enable row level security;' || nl;
  end loop;
  for r in
    select * from pg_policies where schemaname = 'public' order by tablename, policyname
  loop
    v := v || 'create policy ' || quote_ident(r.policyname) || ' on public.' || quote_ident(r.tablename)
      || ' as ' || lower(r.permissive) || ' for ' || lower(r.cmd) || ' to ' || array_to_string(r.roles, ', ')
      || coalesce(nl || '  using (' || r.qual || ')', '')
      || coalesce(nl || '  with check (' || r.with_check || ')', '') || ';' || nl;
  end loop;

  v := v || nl || '-- [declencheurs]' || nl;
  for r in
    select pg_get_triggerdef(t.oid) as def
    from pg_trigger t join pg_class c on c.oid = t.tgrelid
    where c.relnamespace = 'public'::regnamespace and not t.tgisinternal
    order by c.oid, t.tgname
  loop
    v := v || r.def || ';' || nl;
  end loop;

  v := v || nl || '-- [droits]' || nl;
  for r in
    select c.relname,
      (select string_agg(lower(g.privilege_type), ', ' order by g.privilege_type)
         from information_schema.role_table_grants g
         where g.table_schema = 'public' and g.table_name = c.relname and g.grantee = 'anon') as anon,
      (select string_agg(lower(g.privilege_type), ', ' order by g.privilege_type)
         from information_schema.role_table_grants g
         where g.table_schema = 'public' and g.table_name = c.relname and g.grantee = 'authenticated') as auth
    from pg_class c
    where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'v') order by c.oid
  loop
    v := v || 'revoke all on table public.' || quote_ident(r.relname) || ' from anon, authenticated;' || nl
      || coalesce('grant ' || r.anon || ' on table public.' || quote_ident(r.relname) || ' to anon;' || nl, '')
      || coalesce('grant ' || r.auth || ' on table public.' || quote_ident(r.relname) || ' to authenticated;' || nl, '');
  end loop;
  for r in
    select 'public.' || quote_ident(p.proname) || '(' || pg_get_function_identity_arguments(p.oid) || ')' as sig,
           has_function_privilege('anon', p.oid, 'execute') as anon,
           has_function_privilege('authenticated', p.oid, 'execute') as auth,
           has_function_privilege('service_role', p.oid, 'execute') as service
    from pg_proc p
    where p.pronamespace = 'public'::regnamespace and p.prokind = 'f' order by p.proname, p.oid
  loop
    v := v || 'revoke execute on function ' || r.sig || ' from public, anon, authenticated, service_role;' || nl;
    if r.anon or r.auth or r.service then
      v := v || 'grant execute on function ' || r.sig || ' to '
        || concat_ws(', ', case when r.anon then 'anon' end, case when r.auth then 'authenticated' end, case when r.service then 'service_role' end)
        || ';' || nl;
    end if;
  end loop;

  v := v || nl || '-- [taches programmees]' || nl;
  for r in select jobname, schedule, command from cron.job order by jobname loop
    v := v || 'select cron.schedule(' || quote_literal(r.jobname) || ', ' || quote_literal(r.schedule) || ', ' || quote_literal(r.command) || ');' || nl;
  end loop;

  return v;
end;
$function$;
revoke execute on function public.exporter_structure() from public, anon, authenticated;
grant execute on function public.exporter_structure() to service_role;
